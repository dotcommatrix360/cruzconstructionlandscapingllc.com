// hosting-files — Astro integration (local, zero dependencies).
// After `astro build` it writes the files the hosts need into dist/, all derived from one source of truth:
//   sitemap.xml   every built page that is indexable (no robots noindex, not 404, self-canonical)
//   robots.txt    allow all + Sitemap line (skipped if public/robots.txt exists)
//   _redirects    Cloudflare Pages: site.config.json redirects + hide .htaccess (Cloudflare would serve it)
//   .htaccess     Hostinger/Apache: public/.htaccess with the same redirects inserted at "# @redirects"
// The build FAILS on redirect mistakes (missing target, chains, loops, redirecting a page that still exists),
// so a broken redirect map can never reach staging or production.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const xmlEscape = (s) => String(s).replace(/[<>&'"]/g, (ch) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' }[ch]));
const reEscape = (s) => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&');

function walkHtml(dir, base = dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) { if (e.name !== '_astro') walkHtml(full, base, out); }
    else if (e.name.endsWith('.html')) out.push(path.relative(base, full).split(path.sep).join('/'));
  }
  return out.sort();
}

const attr = (tag, name) => (new RegExp(`\\s${name}\\s*=\\s*(["'])([^"']*)\\1`, 'i').exec(tag) || [])[2];
function pageInfo(html) {
  const tags = html.match(/<(meta|link)\b[^>]*>/gi) || [];
  const robots = tags.find((t) => /^<meta/i.test(t) && /name\s*=\s*["']robots["']/i.test(t));
  const canonical = tags.find((t) => /^<link/i.test(t) && /rel\s*=\s*["']canonical["']/i.test(t));
  const modified = tags.find((t) => /property\s*=\s*["']article:modified_time["']/i.test(t)) || tags.find((t) => /property\s*=\s*["']article:published_time["']/i.test(t));
  return {
    noindex: robots ? /noindex/i.test(attr(robots, 'content') || '') : false,
    canonical: canonical ? attr(canonical, 'href') : '',
    lastmod: modified ? (attr(modified, 'content') || '').slice(0, 10) : '',
  };
}

export function normalizeRedirects(list = []) {
  return list
    .filter((r) => r && r.from && r.to)
    .map((r) => ({ from: String(r.from).trim(), to: String(r.to).trim(), status: Number(r.status || 301) }));
}

/** Throws with a readable list when the redirect map is unsafe. `exists(urlPath)` reports built pages. */
export function checkRedirects(redirects, exists) {
  const problems = [];
  const froms = new Map(redirects.map((r) => [r.from.replace(/\*$/, ''), r]));
  for (const r of redirects) {
    if (![301, 302, 307, 308, 410].includes(r.status)) problems.push(`${r.from}: status ${r.status} is not a redirect`);
    if (!r.from.startsWith('/')) problems.push(`${r.from}: "from" must be a root-relative path`);
    if (r.from === r.to) problems.push(`${r.from}: redirects to itself`);
    if (!r.from.endsWith('*') && exists(r.from)) problems.push(`${r.from}: a built page still exists at this URL — remove the page or the redirect`);
    const local = r.to.startsWith('/') ? r.to.split('#')[0].split('?')[0] : null;
    if (local && !/\*|:splat/.test(r.to) && !exists(local)) problems.push(`${r.from} → ${r.to}: target page does not exist`);
    if (local && froms.has(local)) problems.push(`${r.from} → ${r.to}: chain (target redirects again to ${froms.get(local).to}) — point straight at the final URL`);
  }
  return problems;
}

export function redirectsFile(redirects) {
  const lines = ['# Generated by integrations/hosting-files.mjs from site.config.json — edit the config, not this file.', '/.htaccess /404/ 302'];
  for (const r of redirects) lines.push(`${r.from} ${r.to.replace(/\*$/, ':splat')} ${r.status}`);
  return lines.join('\n') + '\n';
}

export function htaccessRedirects(redirects) {
  const lines = ['# Generated from site.config.json redirects (one hop each).'];
  for (const r of redirects) {
    if (r.from.endsWith('*')) {
      const prefix = r.from.slice(0, -1);
      const to = r.to.endsWith('*') ? r.to.slice(0, -1) + '$1' : r.to;
      lines.push(`RedirectMatch ${r.status} ^${reEscape(prefix)}(.*)$ ${to}`);
    } else {
      const bare = r.from.replace(/\/$/, '');
      lines.push(`RedirectMatch ${r.status} ^${reEscape(bare)}/?$ ${r.to}`);
    }
  }
  return lines.join('\n');
}

export default function hostingFiles() {
  let site = '';
  let root = '';
  return {
    name: 'hosting-files',
    hooks: {
      'astro:config:done': ({ config }) => {
        site = String(config.site || '').replace(/\/+$/, '');
        root = fileURLToPath(config.root);
      },
      'astro:build:done': ({ dir, logger }) => {
        const out = fileURLToPath(dir);
        const cfg = JSON.parse(fs.readFileSync(path.join(root, 'site.config.json'), 'utf8'));
        const files = walkHtml(out);
        const urlOf = (rel) => '/' + rel.replace(/(^|\/)index\.html$/, '$1');
        const built = new Set(files.map(urlOf));
        // A folder that only holds sub-pages (e.g. /stories/ with /stories/x/) is not a page.
        const fileExists = (f) => fs.existsSync(f) && (fs.statSync(f).isFile() || fs.existsSync(path.join(f, 'index.html')));
        const exists = (p) => built.has(p) || built.has(p.endsWith('/') ? p : p + '/') || fileExists(path.join(out, p));

        // sitemap.xml — indexable, self-canonical pages only
        const urls = [];
        for (const rel of files) {
          if (/(^|\/)404\.html$/.test(rel)) continue;
          const info = pageInfo(fs.readFileSync(path.join(out, rel), 'utf8'));
          const loc = site + urlOf(rel);
          if (info.noindex) continue;
          if (info.canonical && info.canonical !== loc) continue;
          urls.push(`  <url><loc>${xmlEscape(loc)}</loc>${info.lastmod ? `<lastmod>${info.lastmod}</lastmod>` : ''}</url>`);
        }
        fs.writeFileSync(path.join(out, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`);

        if (!fs.existsSync(path.join(out, 'robots.txt'))) fs.writeFileSync(path.join(out, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`);

        // Redirects → both hosts
        const redirects = normalizeRedirects(cfg.redirects);
        const problems = checkRedirects(redirects, exists);
        if (problems.length) throw new Error(`Redirect map in site.config.json has ${problems.length} problem(s):\n  - ${problems.join('\n  - ')}`);
        fs.writeFileSync(path.join(out, '_redirects'), redirectsFile(redirects));
        const ht = path.join(out, '.htaccess');
        if (fs.existsSync(ht)) {
          const text = fs.readFileSync(ht, 'utf8');
          if (!text.includes('# @redirects')) throw new Error('public/.htaccess has no "# @redirects" marker — restore it from the starter');
          fs.writeFileSync(ht, text.replace('# @redirects', htaccessRedirects(redirects)));
        }
        logger.info(`sitemap.xml: ${urls.length} URL(s) · redirects: ${redirects.length} → _redirects + .htaccess`);
      },
    },
  };
}
