#!/usr/bin/env node
// build.mjs — in-place static build for local business sites.
//   1. Render content collections (_content/*) through _templates/* → article, archive, pagination, category pages
//   2. Expand <!-- @include name --> … <!-- @endinclude --> regions in every HTML page (partials + built-ins)
//   3. Mark current nav links (aria-current), version local CSS/JS (?v=hash)
//   4. Remove stale generated pages, write sitemap.xml
// Usage: node build.mjs [--check] [--quiet]
//   --check  exit 1 if the build would change any file (verifies committed output is current); writes nothing.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, parseArgs, loadConfig, walk, rel, fileToUrlPath, urlPathToFiles, hashFile, escapeHtml, slugify, formatDate, c } from './lib/util.mjs';
import { render } from './lib/template.mjs';
import { parseFrontMatter, markdownToHtml, plainText } from './lib/markdown.mjs';
import { findTags, meta, linkRel } from './lib/html.mjs';

const args = parseArgs();

// Astro projects (agency standard): the framework builds the site into dist/. This command stays the same in
// every repo so the release sequence is identical — it simply runs `npm run build`.
{
  const { detectProject, runBuild, buildState } = await import('./lib/project.mjs');
  const project = detectProject();
  if (project.type === 'astro') {
    if (args.check) {
      const st = buildState(project);
      if (!args.quiet) console.log(st.state === 'fresh' ? c.green(`dist/ is current`) : c.yellow(`dist/ is ${st.state} — run npm run build`));
      process.exit(st.state === 'fresh' ? 0 : 1);
    }
    const r = runBuild(project, { inherit: !args.quiet });
    if (args.quiet && !r.ok) console.error(r.output);
    process.exit(r.ok ? 0 : 1);
  }
}
const CHECK = !!args.check;
const QUIET = !!args.quiet;
const GEN_MARK = 'Generated by local-business-website-builder';
const MANIFEST = path.join(ROOT, '.lbwb-manifest.json');

const cfg = loadConfig();
if (!cfg) {
  console.error(c.red('No site.config.json in the current directory. Run from the repo root, or scaffold with init.mjs.'));
  process.exit(2);
}
const SITE_URL = cfg.site.url;
const notes = [];
const warnings = [];
const changed = [];
const generated = new Set();
const lastmods = new Map(); // url path → ISO date

function write(file, content) {
  let old = null;
  try { old = fs.readFileSync(file, 'utf8'); } catch {}
  if (old === content) return false;
  changed.push(rel(file));
  if (!CHECK) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
  return true;
}

const abs = (u) => (!u ? '' : /^https?:\/\//.test(u) ? u : SITE_URL + (u.startsWith('/') ? u : '/' + u));
const year = new Date().getFullYear();
const prodHost = (() => { try { return new URL(SITE_URL).hostname.replace(/^www\./, ''); } catch { return ''; } })();
const baseCtx = { site: cfg, year, prodHost };

// ---------------------------------------------------------------- schema builders
function prune(o) {
  if (Array.isArray(o)) { const a = o.map(prune).filter((v) => v !== undefined); return a.length ? a : undefined; }
  if (o && typeof o === 'object') {
    const r = {};
    for (const [k, v] of Object.entries(o)) { const p = prune(v); if (p !== undefined) r[k] = p; }
    const keys = Object.keys(r).filter((k) => k !== '@type' && k !== '@context');
    return keys.length ? r : undefined;
  }
  return o === '' || o === null || o === undefined ? undefined : o;
}
const ld = (obj) => `<script type="application/ld+json">${JSON.stringify(prune(obj), null, 2).replace(/</g, '\\u003c')}</script>`;
const businessId = () => `${SITE_URL}/#business`;

function localBusinessSchema() {
  const b = cfg.business;
  const a = b.address || {};
  const hours = (b.hours || []).filter((h) => h.opens && h.closes).map((h) => ({
    '@type': 'OpeningHoursSpecification', dayOfWeek: h.days, opens: h.opens, closes: h.closes,
  }));
  return ld({
    '@context': 'https://schema.org',
    '@type': b.type || 'LocalBusiness',
    '@id': businessId(),
    name: b.name || cfg.site.name,
    legalName: b.legalName,
    description: b.description,
    url: SITE_URL + '/',
    telephone: b.phone,
    email: b.email,
    logo: abs(b.logo),
    image: abs(b.image || b.logo),
    priceRange: b.priceRange,
    address: (a.street || a.city) ? {
      '@type': 'PostalAddress',
      streetAddress: b.hideAddress ? '' : a.street,
      addressLocality: a.city, addressRegion: a.region,
      postalCode: b.hideAddress ? '' : a.postalCode, addressCountry: a.country,
    } : undefined,
    geo: b.geo?.lat && b.geo?.lng && !b.hideAddress ? { '@type': 'GeoCoordinates', latitude: Number(b.geo.lat), longitude: Number(b.geo.lng) } : undefined,
    areaServed: (b.areaServed || []).map((x) => (typeof x === 'string' ? { '@type': 'Place', name: x } : x)),
    openingHoursSpecification: hours,
    sameAs: b.sameAs,
  });
}

function breadcrumbSchema(crumbs) {
  return ld({
    '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: crumbs.map((cr, i) => ({ '@type': 'ListItem', position: i + 1, name: cr.name, item: cr.abs })),
  });
}

// ---------------------------------------------------------------- includes
const partialCache = new Map();
function partial(name) {
  if (!partialCache.has(name)) {
    const f = path.join(ROOT, '_partials', `${name}.html`);
    partialCache.set(name, fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : null);
  }
  return partialCache.get(name);
}

function markCurrent(html, pagePath) {
  return html.replace(/<a\b([^>]*?)href="([^"]*)"([^>]*)>/g, (all, pre, href, post) => {
    if (href !== pagePath || /aria-current=/.test(all)) return all;
    return `<a${pre}href="${href}"${post} aria-current="page">`;
  });
}

function renderInclude(name, pagePath, file) {
  if (name === 'schema:localbusiness') return localBusinessSchema();
  if (name === 'meta:robots') return cfg.site.noindex ? '<meta name="robots" content="noindex, nofollow">' : '';
  const src = partial(name);
  if (src == null) { warnings.push(`${rel(file)}: unknown include "${name}" (no _partials/${name}.html) — left unchanged`); return null; }
  const out = render(src, { ...baseCtx, page: { path: pagePath, url: SITE_URL + pagePath } }).trim();
  return markCurrent(out, pagePath);
}

const START = /<!--\s*@include\s+([\w:./-]+)\s*-->/g;
const END = /<!--\s*@endinclude\s*-->/g;
function expandIncludes(html, pagePath, file) {
  let out = '';
  let pos = 0;
  START.lastIndex = 0;
  let m;
  while ((m = START.exec(html))) {
    const after = m.index + m[0].length;
    END.lastIndex = after;
    const e = END.exec(html);
    const nextStart = html.slice(after).search(/<!--\s*@include\s/);
    const hasEnd = e && (nextStart < 0 || e.index < after + nextStart);
    const regionEnd = hasEnd ? e.index + e[0].length : after;
    const content = renderInclude(m[1], pagePath, file);
    out += html.slice(pos, m.index);
    if (content === null) out += html.slice(m.index, regionEnd);
    else out += content ? `${m[0]}\n${content}\n<!-- @endinclude -->` : `${m[0]}<!-- @endinclude -->`;
    pos = regionEnd;
    START.lastIndex = regionEnd;
  }
  return out + html.slice(pos);
}

function versionAssets(html, file) {
  if (!cfg.build.assetVersioning) return html;
  return html.replace(/\b(href|src)="([^"?#]+\.(?:css|js))(?:\?v=[\w-]*)?"/g, (all, attr, url) => {
    if (/^(https?:)?\/\//.test(url)) return all;
    const target = url.startsWith('/') ? path.join(ROOT, url) : path.join(path.dirname(file), url);
    if (!fs.existsSync(target)) return all;
    return `${attr}="${url}?v=${hashFile(target)}"`;
  });
}

function finalize(html, file) {
  return versionAssets(expandIncludes(html, fileToUrlPath(rel(file)), file), file);
}

function addGeneratedMark(html, source) {
  const mark = `<!-- ${GEN_MARK} from ${source}. Edit the source, not this file. -->`;
  return html.replace(/^(<!doctype html>)/i, `$1\n${mark}`);
}

// ---------------------------------------------------------------- collections
async function buildCollection(col) {
  const srcDir = path.join(ROOT, col.source || `_content/${col.name}`);
  if (!fs.existsSync(srcDir)) { notes.push(`collection "${col.name}": no source folder ${rel(srcDir)} — skipped`); return; }
  const output = (col.output ?? col.name).replace(/^\/+|\/+$/g, '');
  const outBase = output ? `/${output}/` : '/';
  const label = col.label || col.name;
  const itemTplFile = path.join(ROOT, col.itemTemplate || '_templates/article.html');
  const archiveTplFile = path.join(ROOT, col.archiveTemplate || '_templates/archive.html');
  if (!fs.existsSync(itemTplFile)) throw new Error(`collection "${col.name}": missing item template ${rel(itemTplFile)}`);
  const itemTpl = fs.readFileSync(itemTplFile, 'utf8');

  const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.md') && !f.startsWith('_')).sort();
  const items = [];
  const slugs = new Map();
  for (const f of files) {
    const srcRel = rel(path.join(srcDir, f));
    const { data, body } = parseFrontMatter(fs.readFileSync(path.join(srcDir, f), 'utf8'));
    if (data.draft === true) continue;
    for (const req of ['title', 'description', 'date']) if (!data[req]) warnings.push(`${srcRel}: missing front matter "${req}"`);
    const slug = data.slug ? slugify(data.slug) : slugify(f.replace(/\.md$/, '').replace(/^\d{4}-\d{2}-\d{2}-/, ''));
    if (slugs.has(slug)) throw new Error(`collection "${col.name}": duplicate slug "${slug}" in ${srcRel} and ${slugs.get(slug)}`);
    slugs.set(slug, srcRel);
    const date = data.date ? String(data.date).slice(0, 10) : '';
    const updated = data.updated ? String(data.updated).slice(0, 10) : '';
    const category = data.category ? String(data.category) : '';
    const url = col.permalink
      ? col.permalink.replace('{slug}', slug).replace('{yyyy}', date.slice(0, 4)).replace('{mm}', date.slice(5, 7))
        .replace('{dd}', date.slice(8, 10)).replace('{category}', slugify(category || 'general'))
      : `${outBase}${slug}/`;
    const html = await markdownToHtml(body);
    const words = plainText(html).split(' ').filter(Boolean).length;
    const tags = Array.isArray(data.tags) ? data.tags.map(String) : data.tags ? [String(data.tags)] : [];
    if (data.redirectFrom) for (const r of [].concat(data.redirectFrom)) notes.push(`add 301: ${r} → ${url}   (from ${srcRel})`);
    items.push({
      ...data, slug, url, canonical: SITE_URL + url, source: srcRel,
      title: String(data.title || slug), description: String(data.description || ''),
      date, updated, dateDisplay: formatDate(date), updatedDisplay: formatDate(updated),
      category, categorySlug: category ? slugify(category) : '', tags,
      image: data.image || '', imageAlt: data.imageAlt ?? '', imageWidth: data.imageWidth || '', imageHeight: data.imageHeight || '',
      ogImage: abs(data.image || cfg.site.defaultOgImage || ''),
      readingMinutes: Math.max(1, Math.round(words / 220)), noindex: data.noindex === true, html,
    });
  }
  items.sort((a, b) => (b.date || '').localeCompare(a.date || '') || a.title.localeCompare(b.title));

  // Category archives only where there's enough content (avoid thin pages)
  const minCat = col.minCategoryItems ?? 2;
  const byCat = new Map();
  for (const it of items) if (it.category) { if (!byCat.has(it.categorySlug)) byCat.set(it.categorySlug, { name: it.category, items: [] }); byCat.get(it.categorySlug).items.push(it); }
  const archiveEnabled = col.archive !== false && fs.existsSync(archiveTplFile);
  const catArchives = archiveEnabled && col.categories ? [...byCat.entries()].filter(([, v]) => v.items.length >= minCat) : [];
  const catUrl = (s) => `${outBase}category/${s}/`;
  const catHasArchive = new Set(catArchives.map(([s]) => s));
  for (const it of items) it.categoryUrl = it.category && catHasArchive.has(it.categorySlug) ? catUrl(it.categorySlug) : archiveEnabled ? outBase : '';

  const home = { name: 'Home', url: '/', abs: SITE_URL + '/' };
  const archiveCrumb = archiveEnabled ? { name: label, url: outBase, abs: SITE_URL + outBase } : null;

  // Item pages
  for (const it of items) {
    const related = items.filter((o) => o !== it).map((o) => ({
      o, score: (o.category && o.category === it.category ? 3 : 0) + o.tags.filter((t) => it.tags.includes(t)).length,
    })).sort((a, b) => b.score - a.score || (b.o.date || '').localeCompare(a.o.date || '')).slice(0, col.relatedCount ?? 3).map((x) => x.o);
    const crumbs = [home, archiveCrumb, { name: it.title, abs: it.canonical }].filter(Boolean);
    const schemaType = col.schemaType || 'BlogPosting';
    const schema = [
      schemaType === 'none' ? '' : ld({
        '@context': 'https://schema.org', '@type': schemaType, headline: it.title, description: it.description,
        datePublished: it.date, dateModified: it.updated || it.date, image: it.image ? abs(it.image) : undefined,
        author: it.author && it.author !== (cfg.business.name || cfg.site.name) ? { '@type': 'Person', name: it.author } : { '@type': 'Organization', name: cfg.business.name || cfg.site.name, url: SITE_URL + '/' },
        publisher: { '@type': 'Organization', '@id': businessId(), name: cfg.business.name || cfg.site.name, logo: cfg.business.logo ? { '@type': 'ImageObject', url: abs(cfg.business.logo) } : undefined },
        mainEntityOfPage: { '@type': 'WebPage', '@id': it.canonical },
      }),
      breadcrumbSchema(crumbs),
    ].filter(Boolean).join('\n  ');
    const out = render(itemTpl, { ...baseCtx, collection: col, item: it, related, breadcrumbs: crumbs.map(({ name, url }) => ({ name, url })), schema });
    const file = path.join(ROOT, urlPathToFiles(it.url)[0]);
    write(file, finalize(addGeneratedMark(out, it.source), file));
    generated.add(rel(file));
    if (!it.noindex) lastmods.set(it.url, it.updated || it.date);
  }

  // Archive + pagination + category pages
  if (!archiveEnabled) return { name: col.name, items: items.length, archives: 0 };
  const archiveTpl = fs.readFileSync(archiveTplFile, 'utf8');
  const perPage = col.perPage || 9;
  const categoriesNav = catArchives.map(([s, v]) => ({ name: v.name, url: catUrl(s), slug: s }));
  let archivePages = 0;

  const renderList = (list, base, titleBase, h1Base, description, crumbsBase, currentCat) => {
    const totalPages = Math.max(1, Math.ceil(list.length / perPage));
    const pageUrl = (n) => (n === 1 ? base : `${base}page/${n}/`);
    for (let n = 1; n <= totalPages; n++) {
      const url = pageUrl(n);
      const suffix = n > 1 ? ` – Page ${n}` : '';
      const crumbs = n === 1 ? crumbsBase : [...crumbsBase.slice(0, -1), { ...crumbsBase[crumbsBase.length - 1], url: base }, { name: `Page ${n}`, abs: SITE_URL + url }];
      const archive = {
        title: `${titleBase}${suffix} | ${cfg.site.name}`, h1: `${h1Base}${suffix}`, description: n > 1 ? `${description} Page ${n}.` : description,
        canonical: SITE_URL + url, pageNumber: n, totalPages, isFirst: n === 1, ogImage: abs(cfg.site.defaultOgImage || ''),
      };
      const pagination = totalPages > 1 ? {
        prev: n > 1 ? pageUrl(n - 1) : '', next: n < totalPages ? pageUrl(n + 1) : '',
        pages: Array.from({ length: totalPages }, (_, i) => ({ number: i + 1, url: pageUrl(i + 1), current: i + 1 === n })),
      } : { pages: [] };
      const schema = [
        ld({ '@context': 'https://schema.org', '@type': 'CollectionPage', name: archive.h1, description: archive.description, url: archive.canonical }),
        crumbs.length > 1 ? breadcrumbSchema(crumbs) : '',
      ].filter(Boolean).join('\n  ');
      const out = render(archiveTpl, {
        ...baseCtx, collection: col, archive, items: list.slice((n - 1) * perPage, n * perPage), pagination,
        categories: categoriesNav.map((cn) => ({ ...cn, current: cn.slug === currentCat })),
        breadcrumbs: crumbs.map(({ name, url: u }, i) => ({ name, url: i === crumbs.length - 1 ? '' : u })), schema,
      });
      const file = path.join(ROOT, urlPathToFiles(url)[0]);
      write(file, finalize(addGeneratedMark(out, `${rel(srcDir)} (archive)`), file));
      generated.add(rel(file));
      lastmods.set(url, list.slice((n - 1) * perPage, n * perPage).map((i) => i.updated || i.date).sort().pop() || '');
      archivePages++;
    }
  };

  const archiveTitle = col.archiveTitle || label;
  const archiveDesc = col.archiveDescription || `${label} from ${cfg.business.name || cfg.site.name}.`;
  renderList(items, outBase, archiveTitle, archiveTitle, archiveDesc, [home, { name: label, abs: SITE_URL + outBase }], '');
  for (const [s, v] of catArchives) {
    const desc = col.categoryDescriptions?.[v.name] || `${label} articles about ${v.name} from ${cfg.business.name || cfg.site.name}.`;
    renderList(v.items, catUrl(s), `${v.name} | ${label}`, v.name, desc, [home, archiveCrumb, { name: v.name, abs: SITE_URL + catUrl(s) }], s);
  }
  return { name: col.name, items: items.length, archives: archivePages };
}

// ---------------------------------------------------------------- main
const summary = [];
for (const col of cfg.collections) {
  try { const r = await buildCollection(col); if (r) summary.push(r); }
  catch (e) { console.error(c.red(`✖ ${e.message}`)); process.exit(1); }
}

// Remove stale generated files (only files still carrying the generated mark)
const prev = (() => { try { return JSON.parse(fs.readFileSync(MANIFEST, 'utf8')).files || []; } catch { return []; } })();
const removed = [];
for (const f of prev) {
  if (generated.has(f)) continue;
  const full = path.join(ROOT, f);
  try {
    if (!fs.readFileSync(full, 'utf8').includes(GEN_MARK)) continue;
    removed.push(f);
    if (!CHECK) {
      fs.unlinkSync(full);
      let d = path.dirname(full);
      while (d.startsWith(ROOT) && d !== ROOT && fs.readdirSync(d).length === 0) { fs.rmdirSync(d); d = path.dirname(d); }
    }
  } catch {}
}
if (removed.length) changed.push(...removed.map((f) => `${f} (removed)`));

// Expand includes + version assets in every HTML page (generated pages included)
const htmlFiles = walk(ROOT, { ignore: cfg.build.ignore, ext: ['.html'] }).filter((f) => !removed.includes(rel(f)));
let pagesProcessed = 0;
for (const file of htmlFiles) {
  let src;
  try { src = fs.readFileSync(file, 'utf8'); } catch { continue; } // removed in this run
  const pagePath = fileToUrlPath(rel(file));
  let out = expandIncludes(src, pagePath, file);
  out = versionAssets(out, file);
  if (out !== src) write(file, out);
  pagesProcessed++;
}

// Manifest
write(MANIFEST, JSON.stringify({ note: 'Files generated by local-business-website-builder build.mjs. Used to remove stale pages.', files: [...generated].sort() }, null, 2) + '\n');

// Sitemap
let sitemapCount = 0;
if (cfg.build.sitemap !== false) {
  if (!SITE_URL || /^https?:\/\/(www\.)?example\.(com|org|net)$/i.test(SITE_URL)) warnings.push('site.url is not set to the real domain — sitemap and canonicals will be wrong');
  const urls = [];
  for (const file of htmlFiles) {
    const r = rel(file);
    if (/(^|\/)404\.html$/.test(r) || /(^|\/)(google|bing)[\w-]*\.html$/.test(r)) continue;
    let html;
    try { html = fs.readFileSync(file, 'utf8'); } catch { continue; }
    if (CHECK) html = expandIncludes(html, fileToUrlPath(r), file);
    const robots = (meta(html, 'robots') || '').toLowerCase();
    if (robots.includes('noindex')) continue;
    const urlPath = fileToUrlPath(r);
    const expected = SITE_URL + urlPath;
    const canon = linkRel(html, 'canonical')[0]?.attrs.href;
    if (canon && canon !== expected) continue; // canonicalized elsewhere — not a sitemap URL
    urls.push({ loc: expected, lastmod: lastmods.get(urlPath) || '' });
  }
  urls.sort((a, b) => a.loc.length - b.loc.length || a.loc.localeCompare(b.loc));
  const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
    .map((u) => `  <url><loc>${escapeHtml(u.loc)}</loc>${u.lastmod ? `<lastmod>${u.lastmod}</lastmod>` : ''}</url>`).join('\n')}\n</urlset>\n`;
  write(path.join(ROOT, 'sitemap.xml'), xml);
  sitemapCount = urls.length;
}

// Report
if (!QUIET || warnings.length || CHECK) {
  console.log(c.bold('build.mjs') + c.dim(` — ${cfg.site.name || ''}`));
  for (const s of summary) console.log(`  collection ${s.name}: ${s.items} items, ${s.archives} archive pages`);
  console.log(`  pages processed: ${pagesProcessed}, sitemap URLs: ${sitemapCount}`);
  console.log(`  ${CHECK ? 'would change' : 'changed'}: ${changed.length} file(s)`);
  if (!QUIET) for (const f of changed) console.log(c.dim(`    ${f}`));
  for (const n of notes) console.log(c.yellow(`  note: ${n}`));
  for (const w of warnings) console.log(c.yellow(`  warn: ${w}`));
}
if (CHECK && changed.length) {
  console.log(c.red('✖ Build output is not current. Run build.mjs and commit the result.'));
  process.exit(1);
}
